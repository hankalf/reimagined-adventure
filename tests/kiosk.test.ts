import { describe, expect, it } from "vitest";
import jsQR from "jsqr";
import QRCode from "qrcode";
import sharp from "sharp";
import { looksLikeConfirmationCode, parseScanPayload } from "@/lib/kiosk";

describe("parseScanPayload", () => {
  it("normalises plain codes", () => {
    expect(parseScanPayload(" l5zydk ")).toEqual({ code: "L5ZYDK", text: "l5zydk" });
    expect(parseScanPayload("GIFT: 22LQAV")).toEqual({ code: "22LQAV", text: "22LQAV" });
    expect(parseScanPayload("22-LQ-AV").code).toBe("22LQAV");
  });
  it("reads codes out of URLs", () => {
    expect(parseScanPayload("https://gifts.example.com/g/holiday/done?code=ABC234").code).toBe("ABC234");
    expect(parseScanPayload("https://gifts.example.com/pickup/ABC234").code).toBe("ABC234");
  });
  it("leaves employee numbers and names for the fallback lookup", () => {
    expect(parseScanPayload("10001")).toEqual({ code: null, text: "10001" });
    expect(parseScanPayload("Maria Garcia")).toEqual({ code: null, text: "Maria Garcia" });
    expect(parseScanPayload("")).toEqual({ code: null, text: "" });
  });
  it("looksLikeConfirmationCode", () => {
    expect(looksLikeConfirmationCode("abc234")).toBe(true);
    expect(looksLikeConfirmationCode("12")).toBe(false);
  });
});

describe("QR decoding path used by the kiosk camera fallback", () => {
  it("decodes a confirmation-code QR generated by the app", async () => {
    const png = await QRCode.toBuffer("L5ZYDK", { type: "png", width: 300, margin: 2 });
    const { data, info } = await sharp(png).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    const result = jsQR(new Uint8ClampedArray(data.buffer, data.byteOffset, data.byteLength), info.width, info.height);
    expect(result?.data).toBe("L5ZYDK");
    expect(parseScanPayload(result?.data ?? "").code).toBe("L5ZYDK");
  });
});
